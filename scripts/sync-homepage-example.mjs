import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { resolve, dirname } from 'node:path'

// This optional integration example is a snapshot, not a library dependency.
// Run again when the host site's renderer/theme changes.
const repository = fileURLToPath(new URL('..', import.meta.url))
const host = resolve(process.argv.slice(2).filter(argument => argument !== '--')[0] || resolve(repository, '../my-homepage'))
const destination = resolve(repository, 'examples/vue-vite/src/hosts/homepage')
const require = createRequire(import.meta.resolve('vite'))
const presetRequire = createRequire(resolve(repository, 'packages/preset/package.json'))
const postcss = require('postcss')
const files = ['src/utils/markdown.ts', 'src/styles/BDmarkdown.css', 'src/styles/theme.css']
const contents = await Promise.all(files.map(file => readFile(resolve(host, file), 'utf8')))
const [markdown, stylesheet, theme] = contents
const tokens = postcss.root()
postcss.parse(theme.replace(/^\uFEFF/, '')).walkRules(rule => {
  if (!rule.selectors.every(selector => selector === ':root' || /^\[data-color-mode="(?:light|dark)"\]$/.test(selector))) return
  const copy = rule.clone()
  copy.removeAll()
  for (const declaration of rule.nodes) {
    if (declaration.type === 'decl' && declaration.prop.startsWith('--')) copy.append(declaration.clone())
  }
  if (copy.nodes.length) {
    let branch = copy
    let parent = rule.parent
    while (parent && parent.type !== 'root') {
      const shell = parent.clone()
      shell.removeAll()
      shell.append(branch)
      branch = shell
      parent = parent.parent
    }
    tokens.append(branch)
  }
})
// Embed host icons so the example works outside the homepage checkout.
const declarations = []
tokens.walkDecls(declaration => declarations.push(declaration))
for (const declaration of declarations) {
  for (const match of [...declaration.value.matchAll(/url\(['"]?([^)'"]+)['"]?\)/g)]) {
    if (/^(?:https?:|data:)/.test(match[1])) continue
    const asset = await readFile(resolve(host, 'src/styles', match[1]))
    declaration.value = declaration.value.replace(match[0], `url("data:image/svg+xml;base64,${asset.toString('base64')}")`)
  }
}
function scope(root) {
  root.walkRules(rule => {
    if (rule.parent?.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return
    // Retain nested CSS relative to its already scoped parent.
    let parent = rule.parent
    while (parent) { if (parent.type === 'rule') return; parent = parent.parent }
    rule.selectors = rule.selectors.map(selector => selector === ':root' ? '.mde-homepage'
      : /^\[data-color-mode=/.test(selector) ? `.mde-homepage${selector}`
        : `.mde-homepage ${selector}`)
  })
  return root.toString()
}
const styles = postcss.parse(stylesheet.replace(/^\uFEFF/, ''))
const highlight = postcss.parse(await readFile(resolve(dirname(presetRequire.resolve('highlight.js/package.json')), 'styles/github-dark.css'), 'utf8'))
const css = `/* Generated by pnpm run sync:homepage. Host rules are scoped to the demo. */\n${scope(tokens)}\n${scope(styles)}\n${scope(highlight)}\n`
await mkdir(destination, { recursive: true })
await writeFile(resolve(destination, 'markdown.ts'), markdown.replace(/^import 'highlight\.js\/styles\/github-dark\.css';\r?\n/m, ''))
await writeFile(resolve(destination, 'homepage.css'), css)
await writeFile(resolve(destination, 'snapshot.json'), JSON.stringify({
  files: Object.fromEntries(files.map((file, index) => [file, createHash('sha256').update(contents[index]).digest('hex')])),
  note: 'Only the CSS side-effect import is removed from markdown.ts; scoped highlighting is injected with the theme.',
}, null, 2) + '\n')
console.log('Homepage renderer, scoped Markdown CSS, theme variables and icons synced to the standalone playground.')
